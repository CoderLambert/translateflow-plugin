(() => {
  const SOURCE = "translateflow-youtube-bridge";
  const VERSION = 1;
  const MAX_SERIALIZED_PAYLOAD_BYTES = 2 * 1024 * 1024;
  const DIRECTIONS = Object.freeze({ MAIN_TO_ISOLATED: "main-to-isolated", ISOLATED_TO_MAIN: "isolated-to-main" });
  const TYPES = Object.freeze(["READY", "TRACKS", "TIMEDTEXT", "VIDEO_CHANGED", "ERROR", "HELLO", "NUDGE", "STOP"]);
  const BRIDGE_PROTOCOL_GLOBAL = "__TRANSLATE_FLOW_YOUTUBE_BRIDGE_PROTOCOL__";

  function clean(value, max = 512) {
    return String(value ?? "").trim().slice(0, max);
  }

  function isRecord(value) {
    return Boolean(value) && typeof value === "object" && !Array.isArray(value);
  }

  function boundedString(value, max, { allowEmpty = true } = {}) {
    return typeof value === "string" && value.length <= max && (allowEmpty || value.length > 0);
  }

  function byteLength(value) {
    const text = JSON.stringify(value);
    if (typeof TextEncoder === "function") return new TextEncoder().encode(text).byteLength;
    return unescape(encodeURIComponent(text)).length;
  }

  function validTime(value) {
    return value === null || (typeof value === "number" && Number.isFinite(value) && value >= 0);
  }

  function validCue(cue) {
    if (!isRecord(cue) || !boundedString(cue.id, 256, { allowEmpty: false }) || !boundedString(cue.text, 10000, { allowEmpty: false })) return false;
    if (!validTime(cue.startTime) || !validTime(cue.endTime)) return false;
    return cue.startTime === null || cue.endTime === null || cue.endTime >= cue.startTime;
  }

  function validTrack(track) {
    if (track === null) return true;
    if (!isRecord(track)) return false;
    return boundedString(track.id, 256)
      && boundedString(track.kind, 128)
      && boundedString(track.label, 512)
      && boundedString(track.language, 128)
      && boundedString(track.mode, 64)
      && (track.autoGenerated === null || typeof track.autoGenerated === "boolean");
  }

  function validPayload(type, payload) {
    if (!isRecord(payload)) return false;
    switch (type) {
      case "READY":
      case "NUDGE":
      case "STOP":
        return Object.keys(payload).length === 0;
      case "HELLO":
        return Object.keys(payload).every((key) => key === "mode")
          && (payload.mode === undefined || (typeof payload.mode === "string" && ["bilingual", "original", "off"].includes(payload.mode)));
      case "VIDEO_CHANGED":
        return Object.keys(payload).every((key) => key === "reason")
          && (payload.reason === undefined || boundedString(payload.reason, 128, { allowEmpty: false }));
      case "ERROR":
        return Object.keys(payload).every((key) => key === "code" || key === "message")
          && boundedString(payload.code, 128, { allowEmpty: false })
          && boundedString(payload.message, 1000, { allowEmpty: false });
      case "TRACKS":
        return Object.keys(payload).every((key) => ["reason", "tracks", "selected"].includes(key))
          && (payload.reason === undefined || boundedString(payload.reason, 128, { allowEmpty: false }))
          && Array.isArray(payload.tracks)
          && payload.tracks.length <= 64
          && payload.tracks.every(validTrack)
          && validTrack(payload.selected ?? null);
      case "TIMEDTEXT":
        return Object.keys(payload).every((key) => ["format", "cues", "track", "requestUrl"].includes(key))
          && ["json3", "xml", "srv3"].includes(payload.format)
          && Array.isArray(payload.cues)
          && payload.cues.length <= 100000
          && payload.cues.every(validCue)
          && validTrack(payload.track ?? null)
          && (payload.requestUrl === undefined || boundedString(payload.requestUrl, 2048));
      default:
        return false;
    }
  }

  function validateEnvelope(message, options = {}) {
    try {
      return validateEnvelopeUnsafe(message, options);
    } catch {
      return { ok: false, error: "invalid-envelope" };
    }
  }

  function validateEnvelopeUnsafe(message, { direction = "" } = {}) {
    if (!isRecord(message)) return { ok: false, error: "envelope-not-object" };
    if (message.source !== SOURCE || message.version !== VERSION) return { ok: false, error: "protocol-version" };
    if (![DIRECTIONS.MAIN_TO_ISOLATED, DIRECTIONS.ISOLATED_TO_MAIN].includes(message.direction)) return { ok: false, error: "direction" };
    if (direction && message.direction !== direction) return { ok: false, error: "direction-mismatch" };
    if (!TYPES.includes(message.type)) return { ok: false, error: "message-type" };
    if (typeof message.videoId !== "string" || message.videoId.length > 256) return { ok: false, error: "video-id" };
    if (!Number.isInteger(message.generation) || message.generation < 0) return { ok: false, error: "generation" };
    if (typeof message.observedAt !== "number" || !Number.isFinite(message.observedAt) || message.observedAt < 0) return { ok: false, error: "observed-at" };
    try {
      if (byteLength(message.payload) > MAX_SERIALIZED_PAYLOAD_BYTES) return { ok: false, error: "payload-too-large" };
    } catch {
      return { ok: false, error: "payload-serialization" };
    }
    if (!validPayload(message.type, message.payload)) return { ok: false, error: "payload" };
    return { ok: true, value: {
      source: SOURCE,
      version: VERSION,
      direction: message.direction,
      type: message.type,
      videoId: message.videoId,
      generation: message.generation,
      observedAt: message.observedAt,
      payload: message.payload
    } };
  }

  function createEnvelope({ direction, type, videoId = "", generation = 0, observedAt = Date.now(), payload = {} } = {}) {
    const result = validateEnvelope({ source: SOURCE, version: VERSION, direction, type, videoId, generation, observedAt, payload });
    return result.ok ? result.value : null;
  }

  function post(target, fields) {
    const envelope = createEnvelope(fields);
    if (!envelope || !target?.postMessage) return { ok: false, error: "invalid-envelope" };
    try {
      target.postMessage(envelope, "*");
      return { ok: true, value: envelope };
    } catch {
      return { ok: false, error: "post-failed" };
    }
  }

  const api = Object.freeze({
    SOURCE,
    VERSION,
    MAX_SERIALIZED_PAYLOAD_BYTES,
    DIRECTIONS,
    TYPES,
    byteLength,
    validCue,
    validTrack,
    validateEnvelope,
    createEnvelope,
    post
  });

  const pageApi = globalThis[BRIDGE_PROTOCOL_GLOBAL];
  if (!pageApi || pageApi.VERSION !== VERSION) globalThis[BRIDGE_PROTOCOL_GLOBAL] = api;
  const app = globalThis.__TRANSLATE_FLOW_CONTENT__;
  if (app) app.modules.youtubeBridgeProtocol = api;
})();
