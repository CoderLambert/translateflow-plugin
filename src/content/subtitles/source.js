(() => {
  const app = globalThis.__TRANSLATE_FLOW_CONTENT__ ||= { modules: {} };
  if (app.modules.subtitleSource) return;

  const SOURCE_KINDS = Object.freeze({
    TEXT_TRACK: "text-track",
    YOUTUBE_TIMEDTEXT: "youtube-timedtext",
    YOUTUBE_DOM: "youtube-dom"
  });

  function cleanCueText(value) {
    return String(value ?? "").replace(/\s+/g, " ").trim();
  }

  function finiteTime(value) {
    if (value === null || value === undefined || value === "") return null;
    const number = Number(value);
    return Number.isFinite(number) && number >= 0 ? number : null;
  }

  function stableHash(value) {
    let hash = 5381;
    const text = String(value ?? "");
    for (let index = 0; index < text.length; index += 1) {
      hash = ((hash << 5) + hash) ^ text.charCodeAt(index);
    }
    return (hash >>> 0).toString(36);
  }

  function normalizeCue(cue, { source = "unknown", index = 0 } = {}) {
    const text = cleanCueText(cue?.text ?? cue?.textContent);
    if (!text) return null;

    const startTime = finiteTime(cue?.startTime);
    const endTime = finiteTime(cue?.endTime);
    const explicitId = cleanCueText(cue?.id);
    const id = explicitId || [
      source,
      startTime ?? "na",
      endTime ?? "na",
      index,
      stableHash(text)
    ].join(":");

    return {
      id,
      startTime,
      endTime,
      text
    };
  }

  function normalizeTrack(track) {
    if (!track) return null;
    const label = cleanCueText(track.label);
    const id = cleanCueText(track.id);
    const language = cleanCueText(track.language ?? track.srclang).toLowerCase();
    const kind = cleanCueText(track.kind).toLowerCase();
    const mode = cleanCueText(track.mode).toLowerCase();
    const autoGenerated = track.autoGenerated === true || kind === "asr" ? true : inferAutoGenerated({ id, label });

    return {
      id,
      kind,
      label,
      language,
      mode,
      autoGenerated
    };
  }

  function inferAutoGenerated({ id = "", label = "" } = {}) {
    const value = `${id} ${label}`.toLowerCase();
    if (/\b(?:asr|auto[- ]?generated|automatic captions?)\b/.test(value)) return true;
    return null;
  }

  function normalizeSnapshot(input = {}) {
    const source = cleanCueText(input.source) || "unknown";
    const cues = Array.from(input.cues || [])
      .map((cue, index) => normalizeCue(cue, { source, index }))
      .filter(Boolean);

    return {
      type: "cues",
      source,
      reason: cleanCueText(input.reason) || "update",
      mediaId: cleanCueText(input.mediaId),
      mediaTime: finiteTime(input.mediaTime),
      seeking: input.seeking === true,
      observedAt: Number.isFinite(Number(input.observedAt)) ? Number(input.observedAt) : Date.now(),
      track: normalizeTrack(input.track),
      cues,
      upcomingCues: selectUpcomingCues(Array.from(input.upcomingCues || [])
        .map((cue, index) => normalizeCue(cue, { source, index })).filter(Boolean), input.mediaTime)
    };
  }

  // Only known, timestamped cues may be translated ahead. Never predict DOM text.
  function selectUpcomingCues(cues, mediaTime) {
    const time = finiteTime(mediaTime);
    if (time === null) return [];
    return cues.filter(cue => cue.startTime !== null && cue.endTime !== null
      && cue.startTime > time && cue.startTime <= time + 12 && cue.endTime > cue.startTime)
      .sort((a, b) => a.startTime - b.startTime).slice(0, 5);
  }

  // Index known timed cues once. Prefix end maxima keep overlaps correct when
  // seeking in either direction, without scanning the full transcript per tick.
  function createCueTimeline(cues = []) {
    const items = cues.map((cue, index) => ({ cue, index, start: Number(cue.startTime),
      end: cue.endTime === null ? Infinity : Number(cue.endTime), maxEnd: -Infinity }))
      .filter(item => Number.isFinite(item.start)).sort((a, b) => a.start - b.start || a.index - b.index);
    let maxEnd = -Infinity;
    for (const item of items) { maxEnd = Math.max(maxEnd, item.end); item.maxEnd = maxEnd; }
    const boundaries = [...new Set(cues.flatMap(cue => [cue.startTime, cue.endTime]).filter(Number.isFinite))].sort((a, b) => a - b);
    function upperBound(values, time, read = item => item) {
      let low = 0, high = values.length;
      while (low < high) {
        const mid = (low + high) >>> 1;
        if (read(values[mid]) <= time) low = mid + 1;
        else high = mid;
      }
      return low;
    }
    function activeAt(time) {
      const active = [];
      for (let index = upperBound(items, time, item => item.start) - 1; index >= 0; index--) {
        const item = items[index];
        if (item.maxEnd <= time) break;
        if (time < item.end) active.push(item);
      }
      return active.sort((a, b) => a.index - b.index).map(item => item.cue);
    }
    function upcomingAt(time) {
      const upcoming = [];
      for (let index = upperBound(items, time, item => item.start); index < items.length && upcoming.length < 5; index++) {
        const item = items[index];
        if (item.start > time + 12) break;
        if (item.cue.startTime !== null && item.cue.endTime !== null && item.end > item.start) upcoming.push(item.cue);
      }
      return upcoming;
    }
    return { activeAt, upcomingAt, nextBoundary: time => boundaries[upperBound(boundaries, time)] };
  }

  function snapshotSignature(snapshot) {
    const normalized = normalizeSnapshot(snapshot);
    return JSON.stringify({
      source: normalized.source,
      mediaId: normalized.mediaId,
      track: normalized.track,
      cues: normalized.cues,
      upcomingCues: normalized.upcomingCues,
      seeking: normalized.seeking
    });
  }

  function createSnapshotEmitter(onSnapshot) {
    let lastSignature = "";
    let lastSnapshot = null;

    function emit(input, { force = false } = {}) {
      const snapshot = normalizeSnapshot(input);
      const signature = snapshotSignature(snapshot);
      if (!force && signature === lastSignature) return lastSnapshot;
      lastSignature = signature;
      lastSnapshot = snapshot;
      if (typeof onSnapshot === "function") onSnapshot(snapshot);
      return snapshot;
    }

    function reset() {
      lastSignature = "";
      lastSnapshot = null;
    }

    function getLastSnapshot() {
      return lastSnapshot;
    }

    return { emit, reset, getLastSnapshot };
  }

  app.modules.subtitleSource = {
    SOURCE_KINDS,
    cleanCueText,
    normalizeCue,
    normalizeTrack,
    normalizeSnapshot,
    selectUpcomingCues,
    snapshotSignature,
    createSnapshotEmitter,
    createCueTimeline
  };
})();
