import { normalizeSourceText } from "./text.js";

const CACHE_PREFIX = "tf-subtitle:v1:";

export function buildSubtitleCacheSource(unit) {
  const track = unit?.track || {};
  const cue = unit?.cue || {};
  const payload = {
    mediaId: String(unit?.mediaId || "").trim(),
    source: String(unit?.source || "").trim(),
    track: {
      id: String(track.id || "").trim(),
      kind: String(track.kind || "").trim(),
      language: String(track.language || "").trim().toLowerCase(),
      autoGenerated: track.autoGenerated === true ? true : null
    },
    cue: {
      id: String(cue.id || "").trim(),
      startTime: finiteTime(cue.startTime),
      endTime: finiteTime(cue.endTime),
      sequence: cueHasTiming(cue) ? null : positiveInteger(unit?.sequence)
    },
    text: normalizeSourceText(unit?.text)
  };
  return `${CACHE_PREFIX}${JSON.stringify(payload)}`;
}


function cueHasTiming(cue) {
  return finiteTime(cue?.startTime) !== null || finiteTime(cue?.endTime) !== null;
}

function finiteTime(value) {
  if (value === null || value === undefined || value === "") return null;
  const number = Number(value);
  return Number.isFinite(number) && number >= 0 ? number : null;
}

function positiveInteger(value) {
  const number = Number(value);
  return Number.isInteger(number) && number > 0 ? number : null;
}
