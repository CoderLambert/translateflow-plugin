import { build } from "vite";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const projections = [
  { entry: "scripts/reading-source-entry.mjs", output: "src/content/reading-source.js", name: "TranslateFlowReadingSource" },
  { entry: "scripts/reading-record-entry.mjs", output: "src/content/reading-record.js", name: "TranslateFlowReadingRecord" }
];
async function source({ entry, name }) {
  const result = await build({ configFile: false, root, logLevel: "silent",
    build: { write: false, target: "chrome102", minify: "esbuild", sourcemap: false,
      lib: { entry: resolve(root, entry), name, formats: ["iife"] } } });
  const chunks = (Array.isArray(result) ? result : [result]).flatMap(bundle => bundle.output).filter(item => item.type === "chunk");
  if (chunks.length !== 1 || chunks[0].imports.length || chunks[0].dynamicImports.length) throw new Error(`${entry} must produce one self-contained classic script`);
  return `// Generated by scripts/reading-content-classic.mjs from the owned Reading Content sources; do not edit.\n${chunks[0].code}`;
}
export async function checkReadingContentClassic() {
  for (const item of projections) if (await readFile(resolve(root, item.output), "utf8") !== await source(item)) throw new Error(`${item.output} is stale; run node scripts/reading-content-classic.mjs`);
}
export async function writeReadingContentClassic() {
  for (const item of projections) await writeFile(resolve(root, item.output), await source(item));
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.includes("--check")) await checkReadingContentClassic(); else await writeReadingContentClassic();
}
