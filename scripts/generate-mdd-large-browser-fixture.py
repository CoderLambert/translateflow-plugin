"""Build a bounded-streaming large synthetic MDX/MDD browser fixture.

MDict headers and key sections are generated by the pinned independent
writemdict checkout. The large MDD record section is emitted in bounded
3 MiB MDict-v2 blocks because the upstream writer only accepts in-memory
record dictionaries. No product compiler, corpus data, or user files are used.
"""

