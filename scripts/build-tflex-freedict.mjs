export const TFLEX_OPFS_INDEXED_PROFILE = "opfs-indexed-v1";
const SOURCE_ID = "freedict-eng-zho";

export async function compileTflexFreeDict({
  archivePath,
  teiPath,
  copyingPath,
  sourceLockPath,
  outDir
}) {
  const output = requiredPath(outDir, "outDir");
  assertSafeOutputDir(output);
  const lock = validateFreeDictSourceLock(JSON.parse(
    await readFile(requiredPath(sourceLockPath, "sourceLockPath"), "utf8")
  ));

  const audit = await auditFreeDictSource({
    archivePath,
    teiPath,
    copyingPath,
    lockPath: sourceLockPath
  });
  validateExactAudit(lock, audit);

  const [teiText, copyingText] = await Promise.all([
    readFile(requiredPath(teiPath, "teiPath"), "utf8"),
    readFile(requiredPath(copyingPath, "copyingPath"), "utf8")
  ]);
  const records = buildFreeDictRecords(teiText);
  if (!records.length) throw new Error("FreeDict TFLex build produced no records");

  await prepareOutputDir(output);
  const indexed = buildIndexedData(records);
  await writeTextFile(output, "entries.dat", indexed.entriesText);
  await writeTextFile(output, "index.dat", indexed.indexText);

  const attributionText = buildAttributionNotice(lock, audit);
  const modificationsText = buildModificationNotice(lock);
  await writeTextFile(output, "THIRD_PARTY_NOTICES.txt", attributionText);
  await writeTextFile(output, "LICENSE_CC_BY_SA_3.0.txt", copyingText);
  await writeTextFile(output, "MODIFICATIONS.txt", modificationsText);

  const files = [
    descriptor("lookup-index", "index.dat", indexed.indexText),
    descriptor("lexical-data", "entries.dat", indexed.entriesText),
    descriptor("notice", "THIRD_PARTY_NOTICES.txt", attributionText),
    descriptor("notice", "LICENSE_CC_BY_SA_3.0.txt", copyingText),
    descriptor("notice", "MODIFICATIONS.txt", modificationsText)
  ].sort(compareFile);

  const source = {
    id: SOURCE_ID,
    version: lock.source.edition,
    provenance: [
      "FreeDict eng-zho " + lock.source.edition,
      "generated by WikDict",
      "base data from Wiktionary via DBnary"
    ].join("; "),
    dataSha512: lock.source.archiveSha512,
    teiSha256: lock.source.tei.sha256,
    dataUrl: lock.source.url,
    license: {
      id: lock.license.id,
      name: lock.license.name,
      source: lock.license.source
    }
  };
  const sources = [source];
  const fingerprintPayload = makeFreeDictFingerprintPayload({
    packId: lock.packId,
    packVersion: lock.packVersion,
    sources,
    files
  });
  const manifest = {
    format: "tflex",
    formatVersion: TFLEX_FORMAT_VERSION,
    readerMinVersion: TFLEX_READER_MIN_VERSION,
    compilerVersion: TFLEX_COMPILER_VERSION,
    normalizationVersion: TFLEX_NORMALIZATION_VERSION,
    packId: lock.packId,
    packVersion: lock.packVersion,
    sourceLanguage: lock.sourceLanguage,
    targetLanguage: lock.targetLanguage,
    profile: TFLEX_OPFS_INDEXED_PROFILE,
    fingerprint: "sha256:" + sha256Text(stableStringify(fingerprintPayload)),
    recordCount: records.length,
    sourceEntryCount: audit.tei.headwords,
    license: {
      id: lock.license.adaptationLicense,
      name: lock.license.name,
      source: lock.license.source
    },
    sources,
    files: files.map(({ text: _text, ...file }) => file)
  };
  await writeTextFile(output, "manifest.json", stableStringify(manifest) + "\n");

  await validateFreeDictPackOutput({ outDir: output });
  return { manifest, index: indexed.index, records, audit };
}

export function validateFreeDictSourceLock(lock) {
  if (!plainObject(lock)) throw new Error("FreeDict source lock must be an object");
  if (lock.schemaVersion !== 1) throw new Error("FreeDict source lock schemaVersion must be 1");
  if (lock.formatVersion !== TFLEX_FORMAT_VERSION) throw new Error("FreeDict source lock formatVersion is incompatible");
  if (lock.readerMinVersion !== TFLEX_READER_MIN_VERSION) throw new Error("FreeDict source lock readerMinVersion is incompatible");
  if (lock.normalizationVersion !== TFLEX_NORMALIZATION_VERSION) throw new Error("FreeDict source lock normalizationVersion is incompatible");
  for (const key of ["packId", "packVersion", "sourceLanguage", "targetLanguage"]) {
    requireText(lock[key], "lock " + key);
  }
  if (lock.packId !== "freedict-eng-zho") throw new Error("unexpected FreeDict packId");
  if (lock.sourceLanguage !== "en" || lock.targetLanguage !== "zh-CN") {
    throw new Error("FreeDict source lock language pair is incompatible");
  }

  const source = lock.source;
  if (!plainObject(source) || source.id !== SOURCE_ID || source.dictionary !== "eng-zho") {
    throw new Error("FreeDict source identity is invalid");
  }
  requireText(source.edition, "FreeDict edition");
  requireText(source.url, "FreeDict source URL");
  requireSha512(source.archiveSha512, "FreeDict archive SHA-512");
  positiveInteger(source.archiveSizeBytes, "FreeDict archive size");

  const tei = source.tei;
  if (!plainObject(tei) || tei.filename !== "eng-zho.tei") throw new Error("FreeDict TEI metadata is invalid");
  requireSha256(tei.sha256, "FreeDict TEI SHA-256");
  positiveInteger(tei.sizeBytes, "FreeDict TEI size");
  positiveInteger(tei.headwords, "FreeDict TEI headword count");
  for (const key of [
    "title", "edition", "publicationDate", "publisher", "maintainer",
    "licenseUrl", "licenseName", "sourceDescription"
  ]) requireText(tei[key], "FreeDict TEI " + key);

  const copying = source.copying;
  if (!plainObject(copying) || copying.filename !== "COPYING") throw new Error("FreeDict COPYING metadata is invalid");
  requireSha256(copying.sha256, "FreeDict COPYING SHA-256");
  positiveInteger(copying.sizeBytes, "FreeDict COPYING size");

  if (
    lock.license?.id !== "CC-BY-SA-3.0" ||
    lock.license?.adaptationLicense !== "CC-BY-SA-3.0" ||
    lock.license?.approvedForOfficialPack !== true ||
    lock.license?.source !== "https://creativecommons.org/licenses/by-sa/3.0/legalcode"
  ) {
    throw new Error("FreeDict official-pack license approval is missing or incompatible");
  }
  requireText(lock.license.name, "FreeDict license name");
  requireText(lock.license.notice, "FreeDict license notice");
  if (lock.qualityRole !== "optional-complement-only") {
    throw new Error("FreeDict source must remain optional-complement-only");
  }
  return lock;
}

export function buildFreeDictRecords(teiText) {
  const source = String(teiText || "");
  const grouped = new Map();
  const entryExpression = /<entry\b[^>]*>([\s\S]*?)<\/entry>/gi;
  let entryMatch;
  let entryIndex = 0;

  while ((entryMatch = entryExpression.exec(source))) {
    entryIndex += 1;
    const entry = entryMatch[1];
    const headword = firstTagText(entry, "orth");
    if (!headword) continue;
    assertDataOnly(headword, "FreeDict headword");
    const lookupKey = normalizeLookupKey(headword);
    if (!lookupKey) continue;

    const partOfSpeech = normalizePartOfSpeech(firstTagText(tagBlock(entry, "gramGrp"), "pos"));
    const aliases = extractInflectedForms(entry);
    const translationsBySense = extractTranslations(entry);
    if (!translationsBySense.length) continue;

    let record = grouped.get(lookupKey);
    if (!record) {
      record = {
        lookupKey,
        exactLookupKeys: new Set(),
        displayForm: headword,
        kind: "lexical",
        aliases: new Set(),
        senses: [],
        senseKeys: new Map()
      };
      grouped.set(lookupKey, record);
    }
    record.exactLookupKeys.add(normalizeExactLookupKey(headword));
    for (const alias of aliases) {
      assertDataOnly(alias, "FreeDict inflected form");
      if (normalizeLookupKey(alias) !== lookupKey) record.aliases.add(alias);
    }

    translationsBySense.forEach((translations, senseIndex) => {
      const normalizedTranslations = unique(
        translations.map((value) => cleanText(value)).filter(Boolean)
      );
      if (!normalizedTranslations.length) return;
      normalizedTranslations.forEach((value) => assertDataOnly(value, "FreeDict translation"));
      const key = (partOfSpeech || "") + "\u0000" + normalizedTranslations.join("\u0000");
      const sourceRef = {
        sourceId: SOURCE_ID,
        recordId: "entry:" + entryIndex + ":sense:" + (senseIndex + 1)
      };
      const existing = record.senseKeys.get(key);
      if (existing) {
        if (!existing.sourceRefs.some((ref) => ref.recordId === sourceRef.recordId)) {
          existing.sourceRefs.push(sourceRef);
        }
        return;
      }
      const sense = {
        id: "freedict:" + entryIndex + ":" + (senseIndex + 1),
        partOfSpeech,
        translations: normalizedTranslations,
        domains: [],
        sourceRefs: [sourceRef]
      };
      record.senses.push(sense);
      record.senseKeys.set(key, sense);
    });
  }

  const records = [...grouped.values()].map((record) => {
    const result = {
      lookupKey: record.lookupKey,
      exactLookupKeys: [...record.exactLookupKeys].filter(Boolean).sort(compareText),
      displayForm: record.displayForm,
      kind: "lexical",
      aliases: [...record.aliases].sort(compareText),
      senses: record.senses.map((sense) => ({
        ...sense,
        sourceRefs: [...sense.sourceRefs].sort(compareSourceRef)
      }))
    };
    validateTflexRecord(result, "freedict-eng-zho", "entries.dat");
    return result;
  }).sort((a, b) => compareText(a.lookupKey, b.lookupKey));

  let previous = "";
  for (const record of records) {
    if (previous && previous >= record.lookupKey) throw new Error("duplicate or unordered FreeDict lookup key");
    previous = record.lookupKey;
  }
  return records;
}

export function buildIndexedData(records) {
  const indexMap = new Map();
  const lines = [];
  let offset = 0;

  for (const record of records) {
    const line = stableStringify(record) + "\n";
    const bytes = Buffer.from(line, "utf8");
    const target = {
      lookupKey: record.lookupKey,
      offset,
      length: bytes.byteLength,
      sha256: sha256Bytes(bytes),
      matchedAlias: false
    };
    lines.push(line);
    addIndexTarget(indexMap, record.lookupKey, record.exactLookupKeys, target);

    for (const alias of Array.isArray(record.aliases) ? record.aliases : []) {
      const aliasKey = normalizeLookupKey(alias);
      const aliasExact = normalizeExactLookupKey(alias);
      if (!aliasKey) continue;
      addIndexTarget(indexMap, aliasKey, [aliasExact], { ...target, matchedAlias: aliasKey !== record.lookupKey });
    }
    offset += bytes.byteLength;
  }

  const entriesText = lines.join("");
  const entries = [...indexMap.values()]
    .map((entry) => ({
      key: entry.key,
      exactLookupKeys: [...entry.exactLookupKeys].filter(Boolean).sort(compareText),
      targets: [...entry.targets.values()]
        .sort((a, b) => compareText(a.lookupKey, b.lookupKey))
    }))
    .sort((a, b) => compareText(a.key, b.key));
  const index = {
    format: "tflex-index",
    formatVersion: TFLEX_FORMAT_VERSION,
    normalizationVersion: TFLEX_NORMALIZATION_VERSION,
    recordCount: records.length,
    entriesBytes: Buffer.byteLength(entriesText),
    entries
  };
  return {
    entriesText,
    index,
    indexText: stableStringify(index) + "\n"
  };
}

export function makeFreeDictFingerprintPayload({ packId, packVersion, sources, files }) {
  return {
    formatVersion: TFLEX_FORMAT_VERSION,
    normalizationVersion: TFLEX_NORMALIZATION_VERSION,
    packId,
    packVersion,
    profile: TFLEX_OPFS_INDEXED_PROFILE,
    sources: [...sources]
      .sort((a, b) => compareText(a.id, b.id))
      .map((source) => ({
        id: source.id,
        version: source.version,
        provenance: source.provenance,
        dataSha512: source.dataSha512,
        teiSha256: source.teiSha256,
        licenseId: source.license?.id
      })),
    files: [...files]
      .sort(compareFile)
      .map(({ role, path, size, sha256 }) => ({ role, path, size, sha256 }))
  };
}

export async function validateFreeDictPackOutput({ outDir }) {
  const root = requiredPath(outDir, "outDir");
  const manifest = JSON.parse(await readFile(resolve(root, "manifest.json"), "utf8"));
  if (
    manifest.format !== "tflex" ||
    manifest.formatVersion !== TFLEX_FORMAT_VERSION ||
    manifest.normalizationVersion !== TFLEX_NORMALIZATION_VERSION ||
    manifest.profile !== TFLEX_OPFS_INDEXED_PROFILE ||
    manifest.packId !== "freedict-eng-zho" ||
    manifest.license?.id !== "CC-BY-SA-3.0"
  ) {
    throw new Error("FreeDict TFLex manifest is incompatible");
  }
  const descriptors = new Map(manifest.files.map((file) => [file.path, file]));
  for (const path of ["index.dat", "entries.dat", "THIRD_PARTY_NOTICES.txt", "LICENSE_CC_BY_SA_3.0.txt", "MODIFICATIONS.txt"]) {
    const descriptor = descriptors.get(path);
    if (!descriptor) throw new Error("FreeDict TFLex descriptor missing: " + path);
    const bytes = await readFile(resolve(root, path));
    if (bytes.byteLength !== descriptor.size || sha256Bytes(bytes) !== descriptor.sha256) {
      throw new Error("FreeDict TFLex descriptor mismatch: " + path);
    }
  }

  const index = JSON.parse(await readFile(resolve(root, "index.dat"), "utf8"));
  const entriesBytes = await readFile(resolve(root, "entries.dat"));
  if (
    index.format !== "tflex-index" ||
    index.formatVersion !== TFLEX_FORMAT_VERSION ||
    index.normalizationVersion !== TFLEX_NORMALIZATION_VERSION ||
    index.recordCount !== manifest.recordCount ||
    index.entriesBytes !== entriesBytes.byteLength ||
    !Array.isArray(index.entries) ||
    !index.entries.length
  ) {
    throw new Error("FreeDict TFLex index is malformed");
  }

  let previous = "";
  let validatedRecords = 0;
  const canonical = new Set();
  for (const item of index.entries) {
    if (!item?.key || normalizeLookupKey(item.key) !== item.key || (previous && previous >= item.key)) {
      throw new Error("FreeDict TFLex index keys are malformed or unordered");
    }
    previous = item.key;
    if (!Array.isArray(item.targets) || !item.targets.length) throw new Error("FreeDict TFLex index target is missing");
    for (const target of item.targets) {
      validateIndexTarget(target, entriesBytes.byteLength);
      if (target.matchedAlias) continue;
      if (canonical.has(target.lookupKey)) continue;
      const bytes = entriesBytes.subarray(target.offset, target.offset + target.length);
      if (sha256Bytes(bytes) !== target.sha256) throw new Error("FreeDict TFLex record hash mismatch");
      const record = JSON.parse(bytes.toString("utf8").trim());
      validateTflexRecord(record, manifest.packId, "entries.dat");
      if (record.lookupKey !== target.lookupKey) throw new Error("FreeDict TFLex index/record key mismatch");
      canonical.add(target.lookupKey);
      validatedRecords += 1;
    }
  }
  if (validatedRecords !== manifest.recordCount) throw new Error("FreeDict TFLex recordCount mismatch");

  const fingerprintPayload = makeFreeDictFingerprintPayload({
    packId: manifest.packId,
    packVersion: manifest.packVersion,
    sources: manifest.sources,
    files: manifest.files
  });
  const actualFingerprint = "sha256:" + sha256Text(stableStringify(fingerprintPayload));
  if (actualFingerprint !== manifest.fingerprint) throw new Error("FreeDict TFLex fingerprint mismatch");
  return { manifest, index, validatedRecords };
}

function validateExactAudit(lock, audit) {
  const tei = lock.source.tei;
  const copying = lock.source.copying;
  const fields = [
    ["TEI SHA-256", audit.tei.sha256, tei.sha256],
    ["TEI size", audit.tei.sizeBytes, tei.sizeBytes],
    ["TEI title", audit.tei.title, tei.title],
    ["TEI edition", audit.tei.edition, tei.edition],
    ["TEI publication date", audit.tei.publicationDate, tei.publicationDate],
    ["TEI headwords", audit.tei.headwords, tei.headwords],
    ["TEI publisher", audit.tei.publisher, tei.publisher],
    ["TEI maintainer", audit.tei.maintainer, tei.maintainer],
    ["TEI license URL", audit.tei.licenseUrl, tei.licenseUrl],
    ["TEI license name", audit.tei.licenseName, tei.licenseName],
    ["TEI source description", audit.tei.sourceDescription, tei.sourceDescription],
    ["COPYING SHA-256", audit.copying.sha256, copying.sha256],
    ["COPYING size", audit.copying.sizeBytes, copying.sizeBytes],
    ["COPYING license", audit.copying.licenseId, lock.license.id]
  ];
  for (const [label, actual, expected] of fields) {
    if (actual !== expected) throw new Error(label + " drift: expected " + expected + ", got " + actual);
  }
  if (!Object.values(audit.provenanceChecks).every(Boolean)) {
    throw new Error("FreeDict source provenance drift");
  }
}

function extractInflectedForms(entry) {
  const aliases = [];
  const expression = /<form\b[^>]*\btype=["']infl["'][^>]*>([\s\S]*?)<\/form>/gi;
  let match;
  while ((match = expression.exec(entry))) {
    const orthExpression = /<orth\b[^>]*>([\s\S]*?)<\/orth>/gi;
    let orth;
    while ((orth = orthExpression.exec(match[1]))) {
      const value = cleanXmlText(orth[1]);
      if (value) aliases.push(value);
    }
  }
  return unique(aliases);
}

function extractTranslations(entry) {
  const result = [];
  const expression = /<cit\b[^>]*\btype=["']trans["'][^>]*>([\s\S]*?)<\/cit>/gi;
  let match;
  while ((match = expression.exec(entry))) {
    const quotes = [];
    const quoteExpression = /<quote\b[^>]*>([\s\S]*?)<\/quote>/gi;
    let quote;
    while ((quote = quoteExpression.exec(match[1]))) {
      const value = cleanXmlText(quote[1]);
      if (value) quotes.push(value);
    }
    if (quotes.length) result.push(unique(quotes));
  }
  return result;
}

function addIndexTarget(indexMap, rawKey, exactKeys, target) {
  const key = normalizeLookupKey(rawKey);
  if (!key) return;
  let item = indexMap.get(key);
  if (!item) {
    item = { key, exactLookupKeys: new Set(), targets: new Map() };
    indexMap.set(key, item);
  }
  for (const exact of exactKeys || []) if (exact) item.exactLookupKeys.add(exact);
  const existing = item.targets.get(target.lookupKey);
  if (!existing || (existing.matchedAlias && !target.matchedAlias)) {
    item.targets.set(target.lookupKey, target);
  }
}

function validateIndexTarget(target, entriesBytes) {
  if (
    !target ||
    !target.lookupKey ||
    normalizeLookupKey(target.lookupKey) !== target.lookupKey ||
    !Number.isSafeInteger(target.offset) ||
    target.offset < 0 ||
    !Number.isSafeInteger(target.length) ||
    target.length <= 0 ||
    target.offset + target.length > entriesBytes ||
    !/^[a-f0-9]{64}$/.test(target.sha256 || "") ||
    typeof target.matchedAlias !== "boolean"
  ) {
    throw new Error("FreeDict TFLex index target is malformed");
  }
}

function buildAttributionNotice(lock, audit) {
  return [
    "FreeDict eng-zho optional TFLex data pack",
    "",
    "Source release: FreeDict eng-zho " + lock.source.edition,
    "Source archive: " + lock.source.url,
    "Source archive SHA-512: " + lock.source.archiveSha512,
    "TEI SHA-256: " + audit.tei.sha256,
    "Publisher / maintainer: " + audit.tei.publisher + " / " + audit.tei.maintainer,
    "Upstream provenance: " + audit.tei.sourceDescription,
    "",
    "License: " + lock.license.name + " [" + lock.license.id + "]",
    "License URL: " + lock.license.source,
    "A complete copy of the source license is distributed as LICENSE_CC_BY_SA_3.0.txt.",
    "TFLex transformation details are distributed as MODIFICATIONS.txt.",
    "",
    lock.license.notice,
    ""
  ].join("\n");
}

function buildModificationNotice(lock) {
  return [
    "TranslateFlow TFLex transformation record",
    "",
    "Input: FreeDict " + lock.source.dictionary + " " + lock.source.edition + " TEI source.",
    "Output: immutable TFLex v1 opfs-indexed-v1 lexical data.",
    "",
    "Retained fields:",
    ...lock.modificationPolicy.retain.map((item) => "- " + item),
    "",
    "Fields intentionally omitted from the runtime pack:",
    ...lock.modificationPolicy.recordOmissions.map((item) => "- " + item),
    "",
    "Entries sharing the same normalized headword are grouped into one TFLex lexical record while keeping attributable sourceRef identifiers per retained sense.",
    "Inflected source forms are represented as lookup aliases and do not overwrite canonical headwords.",
    "No semantic rewriting of source translations is performed.",
    ""
  ].join("\n");
}

function descriptor(role, path, text) {
  return {
    role,
    path,
    size: Buffer.byteLength(text),
    sha256: sha256Text(text),
    text
  };
}

function tagBlock(source, tag) {
  const match = String(source || "").match(new RegExp("<" + tag + "\\b[^>]*>([\\s\\S]*?)<\\/" + tag + ">", "i"));
  return match?.[1] || "";
}

function firstTagText(source, tag) {
  const block = tagBlock(source, tag);
  return block ? cleanXmlText(block) : "";
}

function cleanXmlText(value) {
  return decodeXml(String(value || "").replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim());
}

function decodeXml(value) {
  return String(value || "")
    .replace(/&#x([0-9a-f]+);/gi, (_all, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#([0-9]+);/g, (_all, decimal) => String.fromCodePoint(parseInt(decimal, 10)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

function normalizePartOfSpeech(value) {
  const text = cleanText(value).toLowerCase();
  return ({
    adj: "adjective",
    adv: "adverb",
    n: "noun",
    pn: "proper-noun",
    v: "verb"
  })[text] || text || null;
}

function cleanText(value) {
  return String(value || "").normalize("NFKC").replace(/\s+/g, " ").trim();
}

function assertDataOnly(value, label) {
  const text = String(value || "");
  if (/<\/?[A-Za-z][^>]*>/u.test(text) || /<!--|<!DOCTYPE\b|<\?/iu.test(text) || /javascript\s*:/iu.test(text)) {
    throw new Error(label + " contains HTML-like markup or an executable scheme");
  }
}

async function prepareOutputDir(path) {
  await mkdir(path, { recursive: true });
  if ((await readdir(path)).length) throw new Error("output directory must be empty");
}

async function writeTextFile(root, relativePath, text) {
  const path = resolve(root, relativePath);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, text, "utf8");
}

function assertSafeOutputDir(path) {
  if (path === resolve(process.cwd()) || path === resolve("/")) throw new Error("refusing unsafe output directory");
}

function requiredPath(value, label) {
  if (!value) throw new Error(label + " is required");
  return resolve(value);
}

function requireText(value, label) {
  if (typeof value !== "string" || !value.trim()) throw new Error(label + " is required");
}

function requireSha256(value, label) {
  if (typeof value !== "string" || !/^[a-f0-9]{64}$/i.test(value)) throw new Error(label + " is invalid");
}

function requireSha512(value, label) {
  if (typeof value !== "string" || !/^[a-f0-9]{128}$/i.test(value)) throw new Error(label + " is invalid");
}

function positiveInteger(value, label) {
  if (!Number.isSafeInteger(value) || value <= 0) throw new Error(label + " must be a positive integer");
}

function plainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function compareFile(a, b) {
  return compareText(a.path, b.path) || compareText(a.role, b.role);
}

function compareSourceRef(a, b) {
  return compareText(a.sourceId, b.sourceId) || compareText(a.recordId, b.recordId);
}

function compareText(a, b) {
  const left = String(a ?? "");
  const right = String(b ?? "");
  return left < right ? -1 : left > right ? 1 : 0;
}

function unique(values) {
  return [...new Set(values)];
}

function sha256Bytes(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function sha256Text(text) {
  return sha256Bytes(Buffer.from(text, "utf8"));
}

function parseArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    if (!argv[index].startsWith("--")) continue;
    const key = argv[index].slice(2);
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) throw new Error("missing value for --" + key);
    result[key] = value;
    index += 1;
  }
  return result;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const result = await compileTflexFreeDict({
    archivePath: args.archive,
    teiPath: args.tei,
    copyingPath: args.copying,
    sourceLockPath: args["source-lock"],
    outDir: args.out
  });
  process.stdout.write(JSON.stringify({
    packId: result.manifest.packId,
    packVersion: result.manifest.packVersion,
    fingerprint: result.manifest.fingerprint,
    recordCount: result.manifest.recordCount,
    sourceEntryCount: result.manifest.sourceEntryCount,
    indexEntries: result.index.entries.length
  }, null, 2) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main().catch((error) => {
    console.error(error?.stack || error);
    process.exitCode = 1;
  });
}
