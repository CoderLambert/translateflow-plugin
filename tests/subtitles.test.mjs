test("YouTube source emits only active MAIN timedtext cues and rejects stale video generations", async t => {
  const doc = new FakeEventTarget();
  const win = new FakeEventTarget();
  win.location = { href: "https://www.youtube.com/watch?v=active-a" };
  win.MutationObserver = FakeMutationObserver;
  const video = Object.assign(new FakeEventTarget(), {
    currentTime: 0.5,
    currentSrc: "blob:active-a",
    playbackRate: 1,
    textTracks: Object.assign(new FakeEventTarget(), arrayLike([]))
  });
  const playerRoot = { querySelector: (selector) => selector.startsWith("video") ? video : null };
  doc.documentElement = playerRoot;
  doc.querySelector = (selector) => {
    if (selector === "#movie_player" || selector === ".html5-video-player") return playerRoot;
    if (selector.startsWith("video")) return video;
    return null;
  };
  const { youtubeSubtitleSource, youtubeBridgeProtocol } = loadModules({ document: doc, window: win });
  const events = [];
  const source = youtubeSubtitleSource.createYouTubeSubtitleSource({ document: doc, window: win, onSnapshot: (event) => events.push(event) });
  t.after(() => source.stop());
  await source.start();

  function send(type, videoId, generation, payload) {
    youtubeBridgeProtocol.post(win, {
      direction: youtubeBridgeProtocol.DIRECTIONS.MAIN_TO_ISOLATED,
      type,
      videoId,
      generation,
      observedAt: 1,
      payload
    });
  }

  send("READY", "active-a", 1, {});
  send("TIMEDTEXT", "active-a", 1, {
    format: "json3",
    track: { id: "yt:en", kind: "captions", label: "English", language: "en", mode: "showing", autoGenerated: null },
    cues: [
      { id: "yt:0:1000:0", startTime: 0, endTime: 1, text: "A one" },
      { id: "yt:1000:1000:1", startTime: 1, endTime: 2, text: "A two" }
    ]
  });
  assert.equal(source.getMode(), "youtube-timedtext");
  assert.equal(events.at(-1).cues[0].text, "A one");
  assert.deepEqual(Array.from(events.at(-1).upcomingCues || [], cue => cue.text), ["A two"]);

  video.currentTime = 1.5;
  video.dispatchEvent({ type: "timeupdate" });
  assert.equal(events.at(-1).cues[0].text, "A two");
  assert.equal(events.at(-1).upcomingCues.length, 0);

  win.location.href = "https://www.youtube.com/watch?v=active-b";
  doc.dispatchEvent({ type: "yt-navigate-finish" });
  send("VIDEO_CHANGED", "active-b", 2, { reason: "spa-navigation" });
  const beforeStale = events.length;
  send("TIMEDTEXT", "active-a", 1, {
    format: "json3",
    track: null,
    cues: [{ id: "yt:0:1000:0", startTime: 0, endTime: 1, text: "stale A" }]
  });
  assert.equal(events.length, beforeStale);
  source.stop();
});

