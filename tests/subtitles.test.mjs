class FakeEventTarget {
  constructor() { this.listeners = new Map(); }
  addEventListener(type, listener) {
    const list = this.listeners.get(type) || [];
    list.push(listener);
    this.listeners.set(type, list);
  }
  removeEventListener(type, listener) {
    const list = this.listeners.get(type) || [];
    this.listeners.set(type, list.filter((item) => item !== listener));
  }
  dispatchEvent(event) {
    for (const listener of this.listeners.get(event.type) || []) listener.call(this, event);
  }
  postMessage(data) {
    this.dispatchEvent({ type: "message", source: this, data });
  }
  listenerCount(type) { return (this.listeners.get(type) || []).length; }
}

class FakeMutationObserver {
  static instances = [];
  constructor(callback) {
    this.callback = callback;
    this.root = null;
    this.disconnected = false;
    FakeMutationObserver.instances.push(this);
  }
  observe(root) { this.root = root; }
  disconnect() { this.disconnected = true; }
  trigger() { if (!this.disconnected) this.callback([], this); }
}

function arrayLike(items) {
  const value = { length: items.length, item: (index) => items[index] || null };
  items.forEach((item, index) => { value[index] = item; });
  return value;
}

function loadModules({ document, window, timers = {} } = {}) {
  FakeMutationObserver.instances = [];
  const context = vm.createContext({
    console,
    URL,
    Date,
    MutationObserver: FakeMutationObserver,
    setTimeout,
    clearTimeout,
    ...timers,
    document,
    window,
    __TRANSLATE_FLOW_CONTENT__: { modules: {} }
  });
  for (const file of [SOURCE, TEXT_TRACK, PROTOCOL, TIMEDTEXT, YOUTUBE_DOM, YOUTUBE]) {
    vm.runInContext(readFileSync(file, "utf8"), context);
  }
  return context.__TRANSLATE_FLOW_CONTENT__.modules;
}

